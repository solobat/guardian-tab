/**
 * 判断两个等长字符串是否为同形字替换关系（如 g00gle vs google）
 */
const isHomoglyphMatch = (a: string, b: string): boolean => {
  if (a.length !== b.length) return false
  let diffCount = 0
  for (let i = 0; i < a.length; i++) {
    if (a[i] === b[i]) continue
    diffCount++
    if (diffCount > 2) return false
    const x = a[i]
    const y = b[i]
    if (HOMOGLYPH_MAP[x] !== y && HOMOGLYPH_MAP[y] !== x) return false
  }
  return diffCount > 0
}

/**
 * 判断一个域名是否由另一个域名拼接钓鱼关键词而成
 * （如 googlelogin.com 由 google + login 拼接；仅比较同 TLD 的双段域名，避免误伤）
 */
const isSuspiciousSuffixJoin = (a: string, b: string): boolean => {
  if (a.length <= 4 || b.length <= 4) return false
  const la = a.split('.')
  const lb = b.split('.')
  if (la.length !== lb.length || la.length < 2) return false
  const tld = la[la.length - 1]
  if (tld !== lb[lb.length - 1]) return false

  const nameA = la.slice(0, -1).join('.')
  const nameB = lb.slice(0, -1).join('.')
  let extra = ''
  if (nameA.length > nameB.length && nameA.startsWith(nameB)) {
    extra = nameA.slice(nameB.length)
  } else if (nameB.length > nameA.length && nameB.startsWith(nameA)) {
    extra = nameB.slice(nameA.length)
  } else {
    return false
  }
  return SUSPICIOUS_DOMAIN_WORDS.has(extra.toLowerCase())
}

/**
 * 判断两个主域名是否高度相似（疑似钓鱼 typo 域名）：
 * 1. 编辑距离为 1（gooogle vs google）
 * 2. 等长且为同形字替换（g00gle vs google）
 * 3. 由真实域名拼接钓鱼关键词而成（googlelogin vs google）
 */
export const isTypoSimilar = (a: string, b: string): boolean => {
  const x = a.toLowerCase()
  const y = b.toLowerCase()
  if (x === y) return false
  if (x.length <= 3 || y.length <= 3) return false

  if (isSuspiciousSuffixJoin(x, y)) return true

  const dist = levenshteinDistance(x, y)
  if (dist === 1) return true
  if (dist === 2 && isHomoglyphMatch(x, y)) return true
  return false
}
